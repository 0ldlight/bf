// The tests below describe the content-identity contract of Calculate.
// Expected digests come from fixed published vectors ("", "abc") and from
// values computed with an external tool, not from re-running this package.

// chunkReader serves preset chunks, then io.EOF.
type chunkReader struct {
	chunks [][]byte
	calls  int
}

func (r *chunkReader) Read(p []byte) (int, error) {
	r.calls++
	if r.calls > len(r.chunks) {
		return 0, io.EOF
	}
	return copy(p, r.chunks[r.calls-1]), nil
}

// dataEOFReader returns data and io.EOF from the same Read call.
type dataEOFReader struct {
	data []byte
	done bool
}

func (r *dataEOFReader) Read(p []byte) (int, error) {
	if r.done {
		return 0, io.EOF
	}
	r.done = true
	return copy(p, r.data), io.EOF
}

// failReader returns data together with err on the first Read, then err
// alone. Reading it at all sets used, which tests use to detect reads.
type failReader struct {
	data []byte
	err  error
	used bool
}

func (r *failReader) Read(p []byte) (int, error) {
	r.used = true
	if r.data == nil {
		return 0, r.err
	}
	n := copy(p, r.data)
	r.data = nil
	return n, r.err
}

// trackingCloseReader records whether Close was called.
type trackingCloseReader struct {
	reader io.Reader
	closed bool
}

func (r *trackingCloseReader) Read(p []byte) (int, error) { return r.reader.Read(p) }

func (r *trackingCloseReader) Close() error {
	r.closed = true
	return nil
}

// cappedGenReader streams generated bytes and fails if any single read is
// offered a buffer larger than max. This verifies per-read buffers stay
// bounded; by itself it does not rule out every other form of internal
// buffering.
type cappedGenReader struct {
	size int
	pos  int
	max  int
}

func (r *cappedGenReader) Read(p []byte) (int, error) {
	if len(p) > r.max {
		return 0, errors.New("read buffer exceeded cap")
	}
	n := 0
	for n < len(p) && r.pos < r.size {
		p[n] = byte(r.pos % 251)
		r.pos++
		n++
	}
	if n == 0 {
		return 0, io.EOF
	}
	return n, nil
}

// cancelAfterReadReader cancels via its cancel func while delivering the
// first chunk.
type cancelAfterReadReader struct {
	data   []byte
	cancel context.CancelFunc
	calls  int
}

func (r *cancelAfterReadReader) Read(p []byte) (int, error) {
	r.calls++
	if r.calls == 1 {
		r.cancel()
		return copy(p, r.data), nil
	}
	return 0, errors.New("read after cancellation")
}

func stringsReader(s string) io.Reader { return bytes.NewBufferString(s) }

func TestCalculateKnownVectors(t *testing.T) {
	tests := []struct {
		name   string
		input  string
		sha1   string
		sha256 string
		md5    string
		size   int64
	}{
		{
			name:   "empty",
			input:  "",
			sha1:   "da39a3ee5e6b4b0d3255bfef95601890afd80709",
			sha256: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
			md5:    "d41d8cd98f00b204e9800998ecf8427e",
			size:   0,
		},
		{
			name:   "abc",
			input:  "abc",
			sha1:   "a9993e364706816aba3e25717850c26c9cd0d89d",
			sha256: "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
			md5:    "900150983cd24fb0d6963f7d28e17f72",
			size:   3,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			meta, err := content.Calculate(context.Background(), stringsReader(tt.input))
			if err != nil {
				t.Fatalf("Calculate error = %v, want nil", err)
			}
			if meta.SHA1 != tt.sha1 || meta.SHA256 != tt.sha256 || meta.MD5 != tt.md5 || meta.Size != tt.size {
				t.Fatalf("Calculate = %+v, want digests (%s, %s, %s) size %d",
					meta, tt.sha1, tt.sha256, tt.md5, tt.size)
			}
		})
	}
}

func TestCalculateMultiReadBinary(t *testing.T) {
	r := &chunkReader{chunks: [][]byte{
		{0x00, 0xff, 0x80, 0x7f, 0x0a},
		{0x01, 0x02, 0xfe},
		[]byte("tail\x00binary"),
	}}
	meta, err := content.Calculate(context.Background(), r)
	if err != nil {
		t.Fatalf("Calculate error = %v, want nil", err)
	}
	want := content.Metadata{
		SHA1:   "1bde16963499e9bf4fac14c8c8510d8cefd85723",
		SHA256: "456829686a033a61bddeb82c04abbf98371fd41631e1b03f39f803b936598cae",
		MD5:    "38c65afda3ae8eee19d0f7e6d7919ef7",
		Size:   19,
	}
	if meta != want {
		t.Fatalf("Calculate = %+v, want %+v", meta, want)
	}
	if r.calls != 4 { // 3 data chunks + 1 EOF read
		t.Fatalf("Read calls = %d, want 4", r.calls)
	}
}

func TestCalculateDataAndEOFSameRead(t *testing.T) {
	meta, err := content.Calculate(context.Background(), &dataEOFReader{data: []byte("abc")})
	if err != nil {
		t.Fatalf("Calculate error = %v, want nil", err)
	}
	if meta.SHA1 != "a9993e364706816aba3e25717850c26c9cd0d89d" || meta.Size != 3 {
		t.Fatalf("Calculate = %+v, want abc digests size 3", meta)
	}
}

// Only the literal io.EOF terminates successfully; an error that merely
// contains io.EOF (joined or wrapped) must stay an error.
func TestCalculateJoinedEOFAndErrorStaysError(t *testing.T) {
	sentinel := errors.New("burst")
	r := &failReader{data: []byte("abc"), err: errors.Join(io.EOF, sentinel)}
	meta, err := content.Calculate(context.Background(), r)
	if err == nil {
		t.Fatal("Calculate error = nil, want error for data + errors.Join(io.EOF, sentinel)")
	}
	if !errors.Is(err, sentinel) {
		t.Fatalf("errors.Is(err, sentinel) = false, err = %v", err)
	}
	if meta != (content.Metadata{}) {
		t.Fatalf("Calculate meta = %+v, want zero Metadata on error", meta)
	}
}

