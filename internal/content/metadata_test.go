func TestCalculatePreCancelledContextDoesNotRead(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	r := &failReader{err: errors.New("must not be read")}
	meta, err := content.Calculate(ctx, r)
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("errors.Is(err, context.Canceled) = false, err = %v", err)
	}
	if meta != (content.Metadata{}) {
		t.Fatalf("Calculate meta = %+v, want zero Metadata on error", meta)
	}
	if r.used {
		t.Fatal("source was read despite pre-cancelled context")
	}
}

func TestCalculateCancellationAfterRead(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	r := &cancelAfterReadReader{data: []byte("abc"), cancel: cancel}
	meta, err := content.Calculate(ctx, r)
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("errors.Is(err, context.Canceled) = false, err = %v", err)
	}
	if meta != (content.Metadata{}) {
		t.Fatalf("Calculate meta = %+v, want zero Metadata on error", meta)
	}
	if r.calls != 1 {
		t.Fatalf("Read calls = %d, want 1 (no read after cancellation)", r.calls)
	}
}

func TestCalculateDoesNotCloseSource(t *testing.T) {
	r := &trackingCloseReader{reader: stringsReader("abc")}
	if _, err := content.Calculate(context.Background(), r); err != nil {
		t.Fatalf("Calculate error = %v, want nil", err)
	}
	if r.closed {
		t.Fatal("Calculate closed the caller-owned reader")
	}
}

func TestCalculateLargeInputUsesBoundedReads(t *testing.T) {
	const size = 3<<20 + 12345
	r := &cappedGenReader{size: size, max: 1 << 20}
	meta, err := content.Calculate(context.Background(), r)
	if err != nil {
		t.Fatalf("Calculate error = %v, want nil", err)
	}
	want := content.Metadata{
		SHA1:   "25ad34db1427caefe4c6b84d5a0bb4b0c7134ea1",
		SHA256: "1cdde29b8090c73a27338d4ca7cfd64e3a6433439643d9b311b5a8fb424d122b",
		MD5:    "9afda3619c6d95cf1736926b6416862c",
		Size:   size,
	}
	if meta != want {
		t.Fatalf("Calculate = %+v, want %+v", meta, want)
	}
}
